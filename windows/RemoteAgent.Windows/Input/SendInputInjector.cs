using System.Buffers;
using System.Runtime.InteropServices;
using System.Runtime.Versioning;
using Microsoft.Extensions.Logging;
using RemoteAgent.Core.Abstractions;
using RemoteAgent.Windows.Interop;
using RemoteAgent.Windows.Session;

namespace RemoteAgent.Windows.Input;

/// <summary>
/// Injects mouse and keyboard input with <c>SendInput</c> (§4, §10).
/// </summary>
/// <remarks>
/// <para>Deliberately the dumbest class in the input path. Which monitor a touch is on, how a
/// normalised point becomes an absolute coordinate, what is being held and when to let go are all
/// decided in <c>RemoteAgent.Core.Input.InputController</c>, which has unit tests. What is left
/// here is the translation of an already-resolved event into Windows' <c>INPUT</c> structure —
/// the part that can only be verified on a real desktop, kept as small as it can be.</para>
///
/// <para><b>What this cannot do in an ordinary user process, by Windows' design (§12.1).</b> The
/// first two limits are lifted in the desktop agent, which runs as SYSTEM and follows the input
/// desktop (see <see cref="InputDesktopSwitcher"/>); they still apply to portable mode.</para>
/// <list type="bullet">
/// <item><b>Elevated windows ignore it.</b> User Interface Privilege Isolation drops input sent
/// from this medium-integrity process to a window running as administrator. <c>SendInput</c>
/// reports success regardless, so this cannot even be detected here. The fix is a signed binary
/// with <c>uiAccess</c>, noted in the manifest.</item>
/// <item><b>The secure desktop is out of reach.</b> The lock screen, Ctrl+Alt+Del and UAC consent
/// prompts live on Winlogon's desktop. <see cref="GetDesktopState"/> detects that state so the
/// phone is told why nothing is happening.</item>
/// <item><b>Ctrl+Alt+Del cannot be sent.</b> The secure attention sequence is generated by the
/// keyboard driver stack and recognised below the level injected input enters at.</item>
/// </list>
///
/// <para>Nothing here logs an event's contents. A failure is logged as a count and an error code
/// (§7.5).</para>
/// </remarks>
[SupportedOSPlatform("windows")]
public sealed class SendInputInjector : IInputInjector
{
    /// <summary>Batches up to this size are built on the stack; larger ones use a pooled buffer.</summary>
    private const int StackBatch = 32;

    private readonly ILogger<SendInputInjector> _logger;
    private readonly InputDesktopSwitcher? _desktops;

    /// <summary>Creates the injector.</summary>
    /// <param name="logger">Diagnostic sink.</param>
    /// <param name="desktops">
    /// In the desktop agent, which runs as SYSTEM, moves the injecting thread onto whichever
    /// desktop holds input — so the lock screen, the sign-in screen and UAC prompts can be used
    /// from the phone. Absent or disabled, the limits listed above apply.
    /// </param>
    public SendInputInjector(ILogger<SendInputInjector> logger, InputDesktopSwitcher? desktops = null)
    {
        _logger = logger ?? throw new ArgumentNullException(nameof(logger));
        _desktops = desktops;
    }

    private bool FollowsInputDesktop => _desktops?.Enabled == true;

    /// <inheritdoc />
    public PixelRect GetVirtualScreen() => new(
        NativeMethods.GetSystemMetrics(NativeMethods.SmXVirtualScreen),
        NativeMethods.GetSystemMetrics(NativeMethods.SmYVirtualScreen),
        NativeMethods.GetSystemMetrics(NativeMethods.SmCxVirtualScreen),
        NativeMethods.GetSystemMetrics(NativeMethods.SmCyVirtualScreen));

    /// <inheritdoc />
    public (int X, int Y)? GetCursorPosition()
    {
        // GetCursorPos fails unless the caller is on the input desktop.
        _desktops?.AttachCurrentThread();
        return NativeMethods.GetCursorPos(out NativeMethods.Point point) ? (point.X, point.Y) : null;
    }

    /// <inheritdoc />
    public unsafe InputDesktopState GetDesktopState()
    {
        // Running as SYSTEM and following the input desktop, every desktop is reachable: the lock
        // screen is something to type a password into, not a reason to refuse.
        if (FollowsInputDesktop)
        {
            return InputDesktopState.Normal;
        }

        nint desktop = NativeMethods.OpenInputDesktop(0, false, NativeMethods.DesktopReadObjects);
        if (desktop == nint.Zero)
        {
            // Access denied is the secure desktop: this process has no rights on Winlogon's
            // desktop, which is precisely the protection. Any other failure is not evidence of
            // anything, and refusing input on a guess would be worse than trying.
            return Marshal.GetLastPInvokeError() == NativeMethods.ErrorAccessDenied
                ? InputDesktopState.Secure
                : InputDesktopState.Normal;
        }

        try
        {
            const int capacity = 64;
            char* name = stackalloc char[capacity];

            if (!NativeMethods.GetUserObjectInformation(
                    desktop,
                    NativeMethods.UoiName,
                    name,
                    capacity * sizeof(char),
                    out uint needed) || needed < sizeof(char))
            {
                return InputDesktopState.Normal;
            }

            // The user's desktop is always named "Default". Anything else that holds input — the
            // "Winlogon" desktop, the password-protected "Screen-saver" desktop — is one this
            // process cannot inject into.
            var actual = new ReadOnlySpan<char>(name, (int)(needed / sizeof(char)) - 1);
            return actual.Equals("Default", StringComparison.OrdinalIgnoreCase)
                ? InputDesktopState.Normal
                : InputDesktopState.Secure;
        }
        finally
        {
            NativeMethods.CloseDesktop(desktop);
        }
    }

    /// <inheritdoc />
    public unsafe bool Send(ReadOnlySpan<InputEvent> events)
    {
        if (events.IsEmpty)
        {
            return true;
        }

        // SendInput delivers to the calling thread's desktop and fails when that is not the one
        // receiving input. Commands arrive on pool threads, so each send checks its own thread.
        _desktops?.AttachCurrentThread();

        // "Left" on the wire means the primary button. SendInput's LEFTDOWN means the physical
        // left switch, which a left-handed setup has made the secondary one.
        bool swapped = NativeMethods.GetSystemMetrics(NativeMethods.SmSwapButton) != 0;

        NativeMethods.Input[]? rented = null;
        Span<NativeMethods.Input> inputs = events.Length <= StackBatch
            ? stackalloc NativeMethods.Input[events.Length]
            : (rented = ArrayPool<NativeMethods.Input>.Shared.Rent(events.Length)).AsSpan(0, events.Length);

        try
        {
            for (int i = 0; i < events.Length; i++)
            {
                inputs[i] = Translate(events[i], swapped);
            }

            uint sent;
            fixed (NativeMethods.Input* first = inputs)
            {
                sent = NativeMethods.SendInput((uint)inputs.Length, first, sizeof(NativeMethods.Input));
            }

            if (sent == (uint)inputs.Length)
            {
                return true;
            }

            // Debug, not Warning: this happens for every command while a UAC prompt is up, and the
            // phone is told the reason through the command's own error code.
            _logger.LogDebug(
                "SendInput accepted {Sent} of {Count} event(s). Win32 error {Error}.",
                sent,
                inputs.Length,
                Marshal.GetLastPInvokeError());

            return false;
        }
        finally
        {
            if (rented is not null)
            {
                // Cleared before it goes back: the buffer held key codes and typed characters.
                ArrayPool<NativeMethods.Input>.Shared.Return(rented, clearArray: true);
            }
        }
    }

    private static NativeMethods.Input Translate(InputEvent input, bool swapped)
    {
        var native = default(NativeMethods.Input);

        switch (input.Kind)
        {
            case InputEventKind.MouseMoveAbsolute:
                native.Type = NativeMethods.InputMouse;
                native.Data.Mouse.Dx = input.X;
                native.Data.Mouse.Dy = input.Y;
                native.Data.Mouse.Flags = NativeMethods.MouseEventMove |
                                          NativeMethods.MouseEventAbsolute |
                                          NativeMethods.MouseEventVirtualDesk;
                break;

            case InputEventKind.MouseButton:
                native.Type = NativeMethods.InputMouse;
                native.Data.Mouse.Flags = ButtonFlag(input.Button, input.Down, swapped);
                break;

            case InputEventKind.WheelVertical:
                native.Type = NativeMethods.InputMouse;
                native.Data.Mouse.MouseData = unchecked((uint)input.X);
                native.Data.Mouse.Flags = NativeMethods.MouseEventWheel;
                break;

            case InputEventKind.WheelHorizontal:
                native.Type = NativeMethods.InputMouse;
                native.Data.Mouse.MouseData = unchecked((uint)input.X);
                native.Data.Mouse.Flags = NativeMethods.MouseEventHWheel;
                break;

            case InputEventKind.Key:
                native.Type = NativeMethods.InputKeyboard;
                native.Data.Keyboard.VirtualKey = (ushort)input.X;

                // The scan code travels with the virtual key. Windows acts on the virtual key, but
                // games, terminals and remote-desktop clients read the scan code, and an event
                // without one is a key that did not come from any keyboard.
                native.Data.Keyboard.ScanCode =
                    (ushort)NativeMethods.MapVirtualKey((uint)input.X, NativeMethods.MapVkToVsc);

                native.Data.Keyboard.Flags =
                    (RemoteAgent.Core.Input.VirtualKeys.IsExtended(input.X) ? NativeMethods.KeyEventExtendedKey : 0) |
                    (input.Down ? 0 : NativeMethods.KeyEventKeyUp);
                break;

            case InputEventKind.Unicode:
                native.Type = NativeMethods.InputKeyboard;
                native.Data.Keyboard.VirtualKey = 0;
                native.Data.Keyboard.ScanCode = (ushort)input.X;
                native.Data.Keyboard.Flags =
                    NativeMethods.KeyEventUnicode | (input.Down ? 0 : NativeMethods.KeyEventKeyUp);
                break;
        }

        return native;
    }

    private static uint ButtonFlag(MouseButton button, bool down, bool swapped)
    {
        if (swapped && button != MouseButton.Middle)
        {
            button = button == MouseButton.Left ? MouseButton.Right : MouseButton.Left;
        }

        return button switch
        {
            MouseButton.Right => down ? NativeMethods.MouseEventRightDown : NativeMethods.MouseEventRightUp,
            MouseButton.Middle => down ? NativeMethods.MouseEventMiddleDown : NativeMethods.MouseEventMiddleUp,
            _ => down ? NativeMethods.MouseEventLeftDown : NativeMethods.MouseEventLeftUp,
        };
    }
}
