package com.pcremote.remote_control_app.host

import android.util.Base64
import android.util.Log
import java.io.ByteArrayInputStream
import java.io.IOException
import java.io.InputStream
import java.io.OutputStream
import java.net.InetSocketAddress
import java.net.Socket
import java.security.KeyFactory
import java.security.KeyStore
import java.security.MessageDigest
import java.security.cert.CertificateException
import java.security.cert.CertificateFactory
import java.security.cert.X509Certificate
import java.security.spec.PKCS8EncodedKeySpec
import java.util.Date
import java.util.concurrent.atomic.AtomicBoolean
import javax.net.ssl.KeyManagerFactory
import javax.net.ssl.SSLContext
import javax.net.ssl.SSLServerSocket
import javax.net.ssl.SSLSocket
import javax.net.ssl.X509TrustManager

/**
 * The host's TLS listener, mirroring the PC's `ControlChannelListener`.
 *
 * Why this is Kotlin and not Dart: the protocol identifies a viewer by the fingerprint of the
 * self-signed certificate it presents in the TLS handshake. Dart's `SecureServerSocket` can only
 * accept client certificates that chain to a trusted issuer, and a self-signed leaf without
 * `keyCertSign` cannot be made one, so Dart can never complete the handshake, let alone read the
 * fingerprint. Java's TLS stack lets a trust manager decide, so the handshake is done here.
 *
 * Nothing else is. Once a viewer has authenticated, its decrypted bytes are pumped unchanged to a
 * loopback socket the Dart side listens on, preceded by one header line naming the peer:
 *
 * ```
 * PCRH1 <secret> <peerFingerprint> <remoteAddress> <tlsDescription>\n
 * ```
 *
 * The secret was generated by the Dart side for this run and is what stops another app on the
 * phone from connecting to that loopback port and claiming to be a viewer.
 *
 * Only forward-secret AEAD cipher suites are offered, and TLS 1.2 is the floor, as on the PC.
 */
class TlsControlServer(
    certificatePem: String,
    privateKeyPem: String,
    private val preferredPort: Int,
    private val loopbackPort: Int,
    private val secret: String,
) {
    companion object {
        private const val TAG = "PCRemoteHost"
        private const val PORT_FALLBACK_RANGE = 10
        private const val HANDSHAKE_TIMEOUT_MS = 10_000
        private const val HEADER_MAGIC = "PCRH1"

        private val ALLOWED_CIPHER_SUITES = setOf(
            "TLS_AES_128_GCM_SHA256",
            "TLS_AES_256_GCM_SHA384",
            "TLS_CHACHA20_POLY1305_SHA256",
            "TLS_ECDHE_ECDSA_WITH_AES_128_GCM_SHA256",
            "TLS_ECDHE_ECDSA_WITH_AES_256_GCM_SHA384",
            "TLS_ECDHE_ECDSA_WITH_CHACHA20_POLY1305_SHA256",
        )

        private val ALLOWED_PROTOCOLS = setOf("TLSv1.3", "TLSv1.2")

        /** `SHA-256` over the DER certificate, base64url without padding: the one fingerprint. */
        fun fingerprintOf(certificate: X509Certificate): String {
            val digest = MessageDigest.getInstance("SHA-256").digest(certificate.encoded)
            return Base64.encodeToString(digest, Base64.URL_SAFE or Base64.NO_WRAP or Base64.NO_PADDING)
        }
    }

    private val sslContext: SSLContext = buildContext(certificatePem, privateKeyPem)
    private val running = AtomicBoolean(false)
    private var serverSocket: SSLServerSocket? = null
    private var acceptThread: Thread? = null

    /** The bound port. */
    var port: Int = 0
        private set

    /** Binds the preferred port or the next free one after it, and begins accepting. */
    @Synchronized
    fun start(): Int {
        if (running.get()) return port

        val factory = sslContext.serverSocketFactory
        var bound: SSLServerSocket? = null
        var lastError: IOException? = null

        for (candidate in preferredPort..(preferredPort + PORT_FALLBACK_RANGE)) {
            val socket = factory.createServerSocket() as SSLServerSocket
            try {
                socket.reuseAddress = true
                socket.bind(InetSocketAddress(candidate), 16)
                bound = socket
                port = candidate
                break
            } catch (e: IOException) {
                lastError = e
                socket.close()
            }
        }

        val server = bound ?: throw lastError ?: IOException("No free port for the control channel.")

        // Mutual authentication: a viewer without a certificate cannot be matched to a pairing
        // record, so it is refused before any command is parsed.
        server.needClientAuth = true
        server.enabledProtocols = server.supportedProtocols.filter { it in ALLOWED_PROTOCOLS }.toTypedArray()
        server.enabledCipherSuites = server.supportedCipherSuites.filter { it in ALLOWED_CIPHER_SUITES }.toTypedArray()

        serverSocket = server
        running.set(true)

        acceptThread = Thread({ acceptLoop(server) }, "pcremote-tls-accept").apply {
            isDaemon = true
            start()
        }

        Log.i(TAG, "Control channel listening on port $port.")
        return port
    }

    @Synchronized
    fun stop() {
        if (!running.getAndSet(false)) return
        try {
            serverSocket?.close()
        } catch (_: IOException) {
        }
        serverSocket = null
        acceptThread = null
        Log.i(TAG, "Control channel stopped.")
    }

    private fun acceptLoop(server: SSLServerSocket) {
        while (running.get()) {
            val client = try {
                server.accept() as SSLSocket
            } catch (e: IOException) {
                if (running.get()) Log.w(TAG, "Accept failed; continuing.", e)
                continue
            }

            // Each handshake on its own thread: a slow peer must not delay the next viewer.
            Thread({ handleClient(client) }, "pcremote-tls-client").apply {
                isDaemon = true
                start()
            }
        }
    }

    private fun handleClient(client: SSLSocket) {
        val remote = client.inetAddress?.hostAddress ?: "unknown"
        var upstream: Socket? = null

        try {
            client.tcpNoDelay = true
            client.soTimeout = HANDSHAKE_TIMEOUT_MS
            client.startHandshake()
            client.soTimeout = 0

            val session = client.session
            val peer = session.peerCertificates.firstOrNull() as? X509Certificate
            if (peer == null) {
                Log.w(TAG, "Connection from $remote presented no certificate.")
                client.close()
                return
            }

            val fingerprint = fingerprintOf(peer)
            val description = "${session.protocol} ${session.cipherSuite}"
            Log.i(TAG, "Viewer connected from $remote ($description).")

            val loopback = Socket()
            loopback.tcpNoDelay = true
            loopback.connect(InetSocketAddress("127.0.0.1", loopbackPort), 2_000)
            upstream = loopback

            val header = "$HEADER_MAGIC $secret $fingerprint $remote $description\n"
            loopback.getOutputStream().apply {
                write(header.toByteArray(Charsets.US_ASCII))
                flush()
            }

            val toDart = Thread({ pump(client.inputStream, loopback.getOutputStream(), client, loopback) }, "pcremote-pump-in")
            toDart.isDaemon = true
            toDart.start()

            pump(loopback.getInputStream(), client.outputStream, client, loopback)
            toDart.join(2_000)
        } catch (e: IOException) {
            // A failed handshake is the normal shape of "something connected that is not our
            // client": a port scanner, a browser, an unpaired device without a certificate.
            Log.i(TAG, "Connection from $remote ended: ${e.message}")
        } catch (e: Exception) {
            Log.w(TAG, "Unexpected failure handling a connection from $remote.", e)
        } finally {
            try { upstream?.close() } catch (_: IOException) {}
            try { client.close() } catch (_: IOException) {}
        }
    }

    /** Copies bytes until either side ends, then closes both so the other pump ends too. */
    private fun pump(input: InputStream, output: OutputStream, a: Socket, b: Socket) {
        val buffer = ByteArray(16 * 1024)
        try {
            while (true) {
                val read = input.read(buffer)
                if (read < 0) break
                output.write(buffer, 0, read)
                output.flush()
            }
        } catch (_: IOException) {
        } finally {
            try { a.close() } catch (_: IOException) {}
            try { b.close() } catch (_: IOException) {}
        }
    }

    private fun buildContext(certificatePem: String, privateKeyPem: String): SSLContext {
        val certificate = CertificateFactory.getInstance("X.509")
            .generateCertificate(ByteArrayInputStream(certificatePem.toByteArray(Charsets.US_ASCII))) as X509Certificate

        val keyBytes = Base64.decode(
            privateKeyPem
                .replace("-----BEGIN PRIVATE KEY-----", "")
                .replace("-----END PRIVATE KEY-----", "")
                .replace(Regex("\\s"), ""),
            Base64.DEFAULT,
        )
        val privateKey = KeyFactory.getInstance("EC").generatePrivate(PKCS8EncodedKeySpec(keyBytes))

        val password = CharArray(0)
        val keyStore = KeyStore.getInstance("PKCS12").apply {
            load(null, null)
            setKeyEntry("host", privateKey, password, arrayOf(certificate))
        }

        val keyManagers = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm()).apply {
            init(keyStore, password)
        }.keyManagers

        return SSLContext.getInstance("TLS").apply {
            init(keyManagers, arrayOf(PinningTrustManager()), null)
        }
    }

    /**
     * Accepts any client certificate that is within its validity window. There is no CA in this
     * system: identity is established one layer up, where the Dart side matches the fingerprint
     * against a pairing record before a single command is accepted (or, for an unknown
     * fingerprint, allows only `pair.request`).
     */
    private class PinningTrustManager : X509TrustManager {
        override fun checkClientTrusted(chain: Array<out X509Certificate>, authType: String) {
            val leaf = chain.firstOrNull() ?: throw CertificateException("No client certificate.")
            leaf.checkValidity(Date())
        }

        override fun checkServerTrusted(chain: Array<out X509Certificate>, authType: String) {
            throw CertificateException("This trust manager is for the server side only.")
        }

        override fun getAcceptedIssuers(): Array<X509Certificate> = emptyArray()
    }
}
